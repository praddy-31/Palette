//! micro, the terminal editor. A colour scheme is a `.micro` file in its own
//! `colorschemes/` folder, picked by name with `"colorscheme"` in `settings.json`
//! (no include, no full paths). So, like Zed: `init` copies Palette's file there as
//! `colorschemes/palette.micro` and sets `"colorscheme": "palette"`; each switch copies
//! the new file over it. micro reads it when it starts (or after `set colorscheme
//! palette` inside it).
//!
//! micro writes `settings.json` only once you change a setting, so `init` creates it
//! when the `micro` folder exists (micro has run once). Its folder is
//! `$MICRO_CONFIG_HOME`, else `$XDG_CONFIG_HOME/micro`, else `~/.config/micro`.

use std::fs;
use std::path::PathBuf;

use super::{BASE, Output, Target};
use crate::paths::Paths;
use crate::system::Outcome;
use crate::wiring::{Setting, Wiring};

pub const TARGET: Target = Target {
    name: "micro",
    output: Some(Output {
        file: "micro.micro",
        template: include_str!("template.micro"),
        // `color-link` lines only: micro's scheme files can't run anything.
        overridable: true,
        finish: None,
    }),
    wiring: Wiring::Setting(Setting {
        configs,
        per_file: false,
        value: |_| crate::jsonc::quoted("palette"),
        read: |text| crate::jsonc::read(text, "colorscheme"),
        write: |text, value| crate::jsonc::write(text, "colorscheme", value),
        prepare: Some(prepare),
        create: true,
    }),
    installed: |_| super::has_program("micro"),
    reload,
    unload: Some(|_| Outcome::Done("your colour scheme from micro's next start".into())),
    ..BASE
};

fn dir(paths: &Paths) -> PathBuf {
    if !paths.is_fake()
        && let Some(own) = std::env::var_os("MICRO_CONFIG_HOME").filter(|v| !v.is_empty())
    {
        return PathBuf::from(own);
    }
    paths.config_home().join("micro")
}

fn configs(paths: &Paths) -> Vec<PathBuf> {
    vec![dir(paths).join("settings.json")]
}

fn scheme_file(paths: &Paths) -> PathBuf {
    dir(paths).join("colorschemes/palette.micro")
}

fn is_ours(text: &str) -> bool {
    text.starts_with("# Generated by Palette")
}

fn install(paths: &Paths) -> Result<(), String> {
    super::copy_ours(paths, "micro.micro", &scheme_file(paths), is_ours)
}

fn prepare(paths: &Paths, remove: bool) -> Result<String, String> {
    let file = scheme_file(paths);
    if remove {
        if fs::read_to_string(&file).is_ok_and(|t| is_ours(&t)) {
            fs::remove_file(&file).map_err(|e| e.to_string())?;
        }
        return Ok("removed colorschemes/palette.micro".into());
    }
    install(paths)?;
    Ok("copied Palette's colours to colorschemes/palette.micro".into())
}

fn reload(paths: &Paths) -> Outcome {
    match install(paths) {
        Ok(()) => Outcome::Done("updated (micro shows it at its next start)".into()),
        Err(e) => Outcome::Failed(e),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn copies_its_own_and_keeps_yours() {
        let tmp = tempfile::tempdir().unwrap();
        let paths = Paths::fake_home(tmp.path());
        fs::create_dir_all(paths.current()).unwrap();
        fs::write(
            paths.current().join("micro.micro"),
            "# Generated by Palette from theme \"x\".\n",
        )
        .unwrap();
        prepare(&paths, false).unwrap();
        assert!(is_ours(&fs::read_to_string(scheme_file(&paths)).unwrap()));
        fs::write(scheme_file(&paths), "color-link default \"#ffffff\"\n").unwrap();
        assert!(matches!(reload(&paths), Outcome::Failed(_)));
        prepare(&paths, true).unwrap();
        assert!(scheme_file(&paths).exists(), "a scheme you wrote stays");
    }
}
