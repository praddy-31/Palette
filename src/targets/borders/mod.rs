use std::path::{Path, PathBuf};

use super::{BASE, Output, Target};
use crate::paths::Paths;
use crate::system::{self, Outcome};
use crate::wiring::{self, Import, Wiring};

pub const TARGET: Target = Target {
    name: "borders",
    output: Some(Output {
        file: "borders.sh",
        template: include_str!("template.sh"),
        overridable: false,
        finish: None,
    }),
    wiring: Wiring::Import(Import::new(configs, line, wiring::at_end)),
    installed: |_| super::has_program("borders"),
    reload,
    unload: Some(unload),
    ..BASE
};

fn configs(paths: &Paths) -> Vec<PathBuf> {
    let rc = paths.config_home().join("borders/bordersrc");
    if rc.is_file() { vec![rc] } else { Vec::new() }
}

/// Appended after the user's own `borders …` call. Calling `borders` while it
/// runs updates the running instance, so these colours win.
fn line(paths: &Paths, generated: &Path) -> String {
    format!(
        "{} && borders active_color=\"$ACTIVE_COLOR\" inactive_color=\"$INACTIVE_COLOR\"",
        wiring::source_line(paths, generated)
    )
}

fn reload(paths: &Paths) -> Outcome {
    // Palette writes the whole bordersrc (Settings → Borders): run it, so the
    // colours it picks from the new theme apply with its options.
    if crate::desktop::is_managed(paths, crate::desktop::Tool::Borders) {
        return crate::desktop::borders::reload(paths);
    }
    if !system::is_running("borders") {
        return Outcome::Skipped("not running".into());
    }
    let generated = paths.current().join("borders.sh");
    let Some(generated) = generated.to_str() else {
        return Outcome::Failed("palette folder path is not valid UTF-8".into());
    };
    // Same command bordersrc runs; the file is generated by Palette, never a theme's.
    let script = "source \"$1\" && borders active_color=\"$ACTIVE_COLOR\" inactive_color=\"$INACTIVE_COLOR\"";
    match system::run("bash", &["-c", script, "palette", generated]) {
        Ok(_) => Outcome::Done("updated".into()),
        Err(e) => Outcome::Failed(e),
    }
}

/// After `init --remove`: run the user's own bordersrc again, which updates
/// the running borders with their original colours. (Their file, run at
/// their request; Palette's lines are already gone from it.)
fn unload(paths: &Paths) -> Outcome {
    if !system::is_running("borders") {
        return Outcome::Skipped("not running".into());
    }
    let Some(rc) = configs(paths).pop() else {
        return Outcome::Skipped("no bordersrc".into());
    };
    match system::run("bash", &[&rc.to_string_lossy()]) {
        Ok(_) => Outcome::Done("back to your bordersrc colours".into()),
        Err(e) => Outcome::Failed(e),
    }
}
