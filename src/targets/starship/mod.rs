//! Starship has no include, so Palette renders a copy of the user's
//! `starship.toml` with a `[palettes.palette]` table added and selected, and
//! points `STARSHIP_CONFIG` at the copy. Colours written as palette names
//! (`bg:blue`, `fg:accent`) follow the theme; raw hex colours stay as they are.
//! The user keeps editing their own file; `palette refresh` re-copies it.

use std::fs;
use std::io::ErrorKind;
use std::path::PathBuf;

use anyhow::{Context, Result};

use super::{BASE, Note, Output, Target};
use crate::paths::Paths;
use crate::system::Outcome;
use crate::wiring::Wiring;

pub const TARGET: Target = Target {
    name: "starship",
    output: Some(Output {
        file: "starship.toml",
        template: include_str!("template.toml"),
        // Starship's `custom` modules run commands.
        overridable: false,
        finish: Some(finish),
    }),
    wiring: Wiring::Shell,
    installed: |_| super::has_program("starship"),
    reload: |_| Outcome::Done("next prompt".into()),
    env,
    doctor,
    ..BASE
};

/// The user's own config (never Palette's copy, even if `STARSHIP_CONFIG`
/// already points there).
fn user_config(paths: &Paths) -> PathBuf {
    paths.config_home().join("starship.toml")
}

fn env(paths: &Paths) -> Vec<String> {
    let file = paths.for_shell(&paths.current().join("starship.toml"));
    vec![format!("export STARSHIP_CONFIG=\"{file}\"")]
}

fn finish(paths: &Paths, rendered: String) -> Result<String> {
    let path = user_config(paths);
    let user = match fs::read_to_string(&path) {
        Ok(text) => Some(text),
        Err(e) if e.kind() == ErrorKind::NotFound => None,
        Err(e) => return Err(e).with_context(|| format!("reading {}", path.display())),
    };
    Ok(merge(user.as_deref(), &rendered))
}

/// The config Starship would get for `user` (not yet saved) in the active
/// theme: for the Prompt page's preview.
pub fn themed(paths: &Paths, user: &str) -> Result<String> {
    let name = crate::state::current_theme(paths)?.context("no theme is active yet")?;
    let theme = crate::theme::load(paths, &name)?;
    let rendered = crate::render::template_text(&theme, paths, "starship")?;
    Ok(merge(Some(user), &rendered))
}

/// Starship colour names Palette maps to theme colours (`peach` → `orange`),
/// from the template's own lines, so presets can be read in theme colours.
pub fn aliases() -> Vec<(String, String)> {
    include_str!("template.toml")
        .lines()
        .filter_map(|l| {
            let (name, rest) = l.split_once(" = \"{{ ")?;
            let key = rest.strip_suffix(" }}\"")?;
            Some((name.trim().to_string(), key.trim().to_string()))
        })
        .collect()
}

const HEADER: &str = "# Generated by Palette from your starship.toml plus the theme's colours.\n\
                      # Edit your own file, then run `palette refresh`.\n";

/// Add Palette's colours to the user's config and select them. Names from
/// the user's own selected palette stay available unless Palette defines
/// them too. A config that doesn't parse is passed through unchanged, so
/// starship reports the error as it did before.
fn merge(user: Option<&str>, rendered: &str) -> String {
    let mut table: toml::Table = match user.map(str::parse::<toml::Table>) {
        None => toml::Table::new(),
        Some(Ok(table)) => table,
        Some(Err(_)) => {
            return format!(
                "{HEADER}# Your starship.toml has a syntax error, so it is copied unchanged.\n{}",
                user.unwrap_or_default()
            );
        }
    };
    let ours: toml::Table = rendered
        .parse()
        .expect("the starship template is valid TOML");
    let ours = ours["palettes"]["palette"]
        .as_table()
        .cloned()
        .unwrap_or_default();

    let selected = table
        .get("palette")
        .and_then(|p| p.as_str())
        .map(str::to_string);
    let mut colours = selected
        .and_then(|name| table.get("palettes")?.get(&name)?.as_table().cloned())
        .unwrap_or_default();
    colours.extend(ours);

    table.insert("palette".into(), "palette".into());
    let palettes = table
        .entry("palettes")
        .or_insert_with(|| toml::Value::Table(toml::Table::new()));
    if let Some(palettes) = palettes.as_table_mut() {
        palettes.insert("palette".into(), toml::Value::Table(colours.clone()));
    }
    let fixed = guard_contrast(&mut table, &colours);
    let note = match fixed.first() {
        Some(example) => format!(
            "# {FIXED_NOTE} {} text colour(s) that would be unreadable in this theme \
             (e.g. `{example}`).\n",
            fixed.len()
        ),
        None => String::new(),
    };
    format!("{HEADER}{note}{table}")
}

const FIXED_NOTE: &str = "Palette changed";

/// Below this contrast prompt text can't be read (the owner's blue-on-blue
/// git segment in Ethereal: 1.15). Light text on a mid blue, as in starship's
/// own presets, is about 2–2.5 and is a style choice, so it's left alone.
const UNREADABLE: f32 = 1.8;

/// Style words that aren't colours.
const ATTRIBUTES: [&str; 9] = [
    "bold",
    "italic",
    "underline",
    "dimmed",
    "inverted",
    "blink",
    "hidden",
    "strikethrough",
    "none",
];

/// Text whose colour pair is unreadable in this theme gets a readable text
/// colour instead (the theme's darkest or brightest, whichever contrasts more).
/// Only styles that name both a text and a background colour are judged, and
/// only for real text: powerline separators (`[](fg:a bg:b)`) are meant to
/// blend. Names come from the theme, so this happens per theme, in the copy;
/// the user's own file is never touched. Returns what was changed.
fn guard_contrast(table: &mut toml::Table, colours: &toml::Table) -> Vec<String> {
    let mut fixed = Vec::new();
    for (key, value) in table.iter_mut() {
        match value {
            toml::Value::Table(t) => fixed.extend(guard_contrast(t, colours)),
            toml::Value::String(s) if key == "style" => {
                if let Some(new) = fix_style(s, colours) {
                    fixed.push(format!("{s} → {new}"));
                    *s = new;
                }
            }
            toml::Value::String(s) if s.contains("](") => {
                let (new, changes) = fix_format(s, colours);
                fixed.extend(changes);
                *s = new;
            }
            _ => {}
        }
    }
    fixed
}

/// `[text](style)` groups in a format string, innermost first.
fn fix_format(format: &str, colours: &toml::Table) -> (String, Vec<String>) {
    let chars: Vec<char> = format.chars().collect();
    let mut open = Vec::new();
    let mut edits = Vec::new(); // (style start, style end, new style)
    let mut i = 0;
    while i < chars.len() {
        match chars[i] {
            '\\' => i += 1,
            '[' => open.push(i),
            ']' if chars.get(i + 1) == Some(&'(') => {
                if let (Some(start), Some(len)) =
                    (open.pop(), chars[i + 2..].iter().position(|c| *c == ')'))
                {
                    let text: String = chars[start + 1..i].iter().collect();
                    let style: String = chars[i + 2..i + 2 + len].iter().collect();
                    let is_text = text.chars().any(|c| c.is_alphanumeric() || c == '$');
                    if is_text && let Some(new) = fix_style(&style, colours) {
                        edits.push((i + 2, i + 2 + len, style, new));
                    }
                }
            }
            _ => {}
        }
        i += 1;
    }
    let mut out = chars;
    let mut changes = Vec::new();
    edits.sort_by_key(|e| std::cmp::Reverse(e.0));
    for (from, to, old, new) in edits {
        out.splice(from..to, new.chars());
        changes.push(format!("{old} → {new}"));
    }
    changes.reverse();
    (out.into_iter().collect(), changes)
}

/// `fg:blue bg:muted` → `fg:bright_foreground bg:muted` when blue on muted
/// is too faint to read.
fn fix_style(style: &str, colours: &toml::Table) -> Option<String> {
    let resolve = |name: &str| -> Option<String> {
        if name.starts_with('#') && name.len() == 7 {
            return Some(name.to_string());
        }
        colours.get(name)?.as_str().map(str::to_string)
    };
    let words: Vec<&str> = style.split_whitespace().collect();
    let fg_at = words
        .iter()
        .position(|w| w.starts_with("fg:") || (!w.contains(':') && !ATTRIBUTES.contains(w)))?;
    let fg = resolve(words[fg_at].trim_start_matches("fg:"))?;
    let bg = words
        .iter()
        .find_map(|w| w.strip_prefix("bg:"))
        .and_then(resolve)?;
    if crate::colour::contrast(&fg, &bg) >= UNREADABLE {
        return None;
    }
    let best = ["darker_background", "bright_foreground"]
        .into_iter()
        .filter_map(|n| Some((n, resolve(n)?)))
        .max_by(|a, b| {
            crate::colour::contrast(&a.1, &bg).total_cmp(&crate::colour::contrast(&b.1, &bg))
        })?;
    let mut words: Vec<String> = words.iter().map(|w| w.to_string()).collect();
    words[fg_at] = format!("fg:{}", best.0);
    Some(words.join(" "))
}

fn doctor(paths: &Paths) -> Vec<Note> {
    let mut notes = Vec::new();
    let user = user_config(paths);
    let copy = paths.current().join("starship.toml");
    let modified = |p: &PathBuf| fs::metadata(p).and_then(|m| m.modified()).ok();
    if let (Some(u), Some(c)) = (modified(&user), modified(&copy))
        && u > c
    {
        notes.push(Note::fix(
            "starship.toml changed since the last switch: run `palette refresh`",
        ));
    }
    if let Ok(copy) = fs::read_to_string(&copy)
        && let Some(line) = copy.lines().find(|l| l.contains(FIXED_NOTE))
    {
        notes.push(Note::info(describe_fixed(line)));
    }
    if let Ok(text) = fs::read_to_string(&user) {
        let found = hex_colours(&text);
        if !found.is_empty() {
            notes.push(Note::info(describe_hex(&found)));
        }
    }
    notes
}

/// The comment Palette wrote in its copy ("Palette changed 2 text colour(s)
/// that would be unreadable in this theme (e.g. `fg:blue bg:muted → fg:x bg:muted`).")
/// as a sentence for the Check list. Informational: it was fixed already.
fn describe_fixed(comment: &str) -> String {
    let count: usize = comment
        .split("changed ")
        .nth(1)
        .and_then(|r| r.split_whitespace().next())
        .and_then(|n| n.parse().ok())
        .unwrap_or(1);
    let example = comment.split('`').nth(1).and_then(describe_change);
    let (what, verb) = if count == 1 {
        ("1 text colour", "would be")
    } else {
        ("text colours", "would be")
    };
    let what = if count == 1 {
        what.to_string()
    } else {
        format!("{count} {what}")
    };
    let used = if count == 1 {
        "uses a readable one"
    } else {
        "uses readable ones"
    };
    let e = example.map(|e| format!(" ({e})")).unwrap_or_default();
    format!(
        "Fixed for you: {what} in your starship.toml {verb} hard to read in this theme, so \
         Palette's copy {used}{e}. Your file is unchanged. If you'd rather choose them \
         yourself, edit starship.toml using palette names (examples/starship.toml is a \
         starting point) or switch starship off in Apps."
    )
}

/// `fg:blue bg:muted → fg:bright_foreground bg:muted` becomes
/// `fg:blue on muted → bright_foreground`.
fn describe_change(change: &str) -> Option<String> {
    let (old, new) = change.split_once(" → ")?;
    let word = |style: &str, prefix: &str| -> Option<String> {
        style
            .split_whitespace()
            .find_map(|w| w.strip_prefix(prefix).map(str::to_string))
    };
    let old_fg = word(old, "fg:").or_else(|| {
        old.split_whitespace()
            .find(|w| !w.contains(':') && !ATTRIBUTES.contains(w))
            .map(str::to_string)
    })?;
    let bg = word(old, "bg:")?;
    let new_fg = word(new, "fg:")?;
    Some(format!("fg:{old_fg} on {bg} → {new_fg}"))
}

fn describe_hex(found: &[(String, String)]) -> String {
    let shown: Vec<String> = found
        .iter()
        .take(3)
        .map(|(hex, section)| format!("{hex} in {section}"))
        .collect();
    let more = found.len().saturating_sub(3);
    let more = if more > 0 {
        format!(" and {more} more")
    } else {
        String::new()
    };
    let (n, are) = if found.len() == 1 {
        (
            "1 colour in your starship.toml is a fixed hex".to_string(),
            "it stays",
        )
    } else {
        (
            format!(
                "{} colours in your starship.toml are fixed hex values",
                found.len()
            ),
            "they stay",
        )
    };
    format!(
        "{n} ({}{more}); {are} the same in every theme. To make it follow themes, use a \
         palette name such as blue or accent.",
        shown.join(", ")
    )
}

/// Every `#rrggbb` colour with the table it is in (`[git_branch]`, or
/// `top level`), in file order. Comment lines are skipped.
fn hex_colours(text: &str) -> Vec<(String, String)> {
    let mut section = "the top level".to_string();
    let mut out = Vec::new();
    for line in text.lines() {
        let t = line.trim();
        if t.starts_with('#') {
            continue;
        }
        if t.starts_with('[')
            && t.ends_with(']')
            && t[1..t.len() - 1]
                .chars()
                .all(|c| c.is_alphanumeric() || "._-\"' ".contains(c))
        {
            section = t.to_string();
            continue;
        }
        for (i, _) in line.match_indices('#') {
            let rest = &line[i + 1..];
            if rest.len() >= 6
                && rest[..6].chars().all(|c| c.is_ascii_hexdigit())
                && !rest[6..].starts_with(|c: char| c.is_ascii_hexdigit())
            {
                out.push((format!("#{}", &rest[..6]), section.clone()));
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const OURS: &str = "[palettes.palette]\nblue = \"#7aa2f7\"\naccent = \"#7aa2f7\"\n";

    #[test]
    fn adds_and_selects_the_palette() {
        let user =
            "format = \"\"\"\n[x](bg:blue)\\\n$all\"\"\"\n\n[git_branch]\nstyle = \"bg:#394260\"\n";
        let out = merge(Some(user), OURS);
        let table: toml::Table = out.parse().unwrap();
        assert_eq!(table["palette"].as_str(), Some("palette"));
        assert_eq!(
            table["palettes"]["palette"]["blue"].as_str(),
            Some("#7aa2f7")
        );
        assert_eq!(table["format"].as_str(), Some("[x](bg:blue)$all"));
        assert_eq!(table["git_branch"]["style"].as_str(), Some("bg:#394260"));
    }

    #[test]
    fn keeps_the_users_own_palette_names() {
        let user = "palette = \"mine\"\n[palettes.mine]\nblue = \"#000000\"\nsky = \"#87ceeb\"\n";
        let table: toml::Table = merge(Some(user), OURS).parse().unwrap();
        let p = &table["palettes"]["palette"];
        assert_eq!(p["blue"].as_str(), Some("#7aa2f7"), "Palette's colour wins");
        assert_eq!(
            p["sky"].as_str(),
            Some("#87ceeb"),
            "the user's extra name stays"
        );
        assert_eq!(table["palette"].as_str(), Some("palette"));
    }

    #[test]
    fn no_config_or_a_broken_one() {
        let table: toml::Table = merge(None, OURS).parse().unwrap();
        assert_eq!(table["palette"].as_str(), Some("palette"));
        let out = merge(Some("format = \"unclosed"), OURS);
        assert!(out.ends_with("format = \"unclosed"));
    }

    #[test]
    fn unreadable_text_gets_a_readable_colour_but_separators_stay() {
        // The owner's prompt in Ethereal: blue text on a blue-grey pill.
        let ours = "[palettes.palette]\nblue = \"#7d82d9\"\nmuted = \"#6d7db6\"\n\
                    darker_background = \"#030610\"\nbright_foreground = \"#ffcead\"\n";
        let user = "format = \"[](fg:blue bg:muted)[[ $branch ](fg:blue bg:muted)]($style)\"\n\
                    [time]\nstyle = \"bold fg:blue bg:muted\"\n";
        let out = merge(Some(user), ours);
        let table: toml::Table = out.parse().unwrap();
        assert_eq!(
            table["format"].as_str(),
            Some("[](fg:blue bg:muted)[[ $branch ](fg:darker_background bg:muted)]($style)")
        );
        assert_eq!(
            table["time"]["style"].as_str(),
            Some("bold fg:darker_background bg:muted")
        );
        assert!(out.contains("Palette changed 2 text colour(s)"), "{out}");
        // Low but legible pairs (peach on blue, 2.4) are a style choice: left alone.
        let fine = "format = \"[ $branch ](fg:bright_foreground bg:blue)\"\n";
        assert!(!merge(Some(fine), ours).contains("Palette changed"));
    }

    #[test]
    fn finds_hex_colours_and_where() {
        let text = "# #aaaaaa in a comment\nformat = \"[x](bg:#769ff0)\"\n[git_branch]\nstyle = \"fg:#a3aed2\"\nx = \"#12345678\"\n";
        assert_eq!(
            hex_colours(text),
            vec![
                ("#769ff0".to_string(), "the top level".to_string()),
                ("#a3aed2".to_string(), "[git_branch]".to_string()),
            ]
        );
    }

    #[test]
    fn notes_read_as_information_with_an_action() {
        let line = "# Palette changed 2 text colour(s) that would be unreadable in this theme \
                    (e.g. `fg:blue bg:muted → fg:bright_foreground bg:muted`).";
        let text = describe_fixed(line);
        assert!(
            text.starts_with("Fixed for you: 2 text colours in your starship.toml"),
            "{text}"
        );
        assert!(
            text.contains("(fg:blue on muted → bright_foreground)"),
            "{text}"
        );
        assert!(text.contains("Your file is unchanged."), "{text}");
        assert!(text.contains("examples/starship.toml") && text.contains("switch starship off"));
        let hex = describe_hex(&[("#769ff0".into(), "[git_branch]".into())]);
        assert!(
            hex.starts_with(
                "1 colour in your starship.toml is a fixed hex (#769ff0 in [git_branch]);"
            ),
            "{hex}"
        );
        assert!(hex.contains("use a palette name such as blue or accent"));
    }
}
