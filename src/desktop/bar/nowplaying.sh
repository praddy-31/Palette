#!/bin/bash
# Palette bar: now playing (ROADMAP 20). The item runs this at start, on wake and every minute: it keeps one
# feeder running (nowplaying.js through osascript, which may read Control Centre's "now playing" because it's
# Apple-signed) and replaces it when the item's settings change. `toggle` and `open` are the item's clicks.
# The feeder writes ~/Library/Caches/palette/nowplaying.state (playing|paused|none, then the player's bundle id)
# for the clicks and for Palette's beat-line helper. Settings arrive as variables:
#   WIDTH=24 (characters)  SCROLL=1|0 (scroll long titles, or cut them with …)  BEATS=5 (0: no beat lines)
# (generated by Palette; edits are replaced when the bar settings change)
export PATH="$PATH:/opt/homebrew/bin"
DIR="$(cd "$(dirname "$0")" && pwd)"
STATE="$HOME/Library/Caches/palette"
mkdir -p "$STATE"

case "$1" in
  toggle)
    # osascript can read the track but its commands are ignored: /usr/bin/perl (Apple-signed) loads
    # Palette's small library, which asks the player in Control Centre (MEDIA: its path in the app).
    [ -f "$MEDIA" ] || exit 0
    PALETTE_MEDIA=toggle exec /usr/bin/perl -e 'use DynaLoader; my $h = DynaLoader::dl_load_file($ARGV[0], 0) or die DynaLoader::dl_error(); my $s = DynaLoader::dl_find_symbol($h, "palette_media") or die "palette_media missing"; DynaLoader::dl_install_xsub("main::palette_media", $s); palette_media();' "$MEDIA" ;;
  open)
    APP=$(sed -n 2p "$STATE/nowplaying.state" 2>/dev/null)
    [ -n "$APP" ] && exec open -b "$APP"
    exit 0 ;;
esac

SB=$(command -v sketchybar) || exit 0
SIG="${WIDTH:-24}|${SCROLL:-1}|${BEATS:-0}"
PIDF="$STATE/nowplaying.pid"
PID=""; OLD=""
[ -f "$PIDF" ] && { read -r PID; read -r OLD; } < "$PIDF"
if [ -z "$PID" ] || [ "$OLD" != "$SIG" ] || ! kill -0 "$PID" 2>/dev/null; then
  [ -n "$PID" ] && kill -TERM -- "-$PID" 2>/dev/null
  set -m # its own process group, so one kill stops it
  nohup /usr/bin/osascript -l JavaScript "$DIR/nowplaying.js" feed "$SB" "$STATE/nowplaying.state" \
    "${WIDTH:-24}" "${SCROLL:-1}" "${BEATS:-0}" >/dev/null 2>&1 &
  printf '%s\n%s\n' "$!" "$SIG" > "$PIDF"
  set +m
fi
